"""Generates the paper's results table and its comparison figure from results/*.pkl.

Writes paper/results_table.tex, which paper/main.tex \\input{}s, so no number in the
paper is transcribed by hand. Also writes figures/fig_arms.png.

  python experiments/paper_assets.py
"""
import glob, os, pickle, sys, collections
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "src"))

SURFACE = "#fcfcfb"
CAT = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300", "#4a3aa7",
       "#e34948"]
INK, INK2, INK3 = "#0b0b0b", "#52514e", "#8a8880"
GOOD, CRIT = "#0ca30c", "#d03b3b"
plt.rcParams.update({
    "figure.facecolor": SURFACE, "axes.facecolor": SURFACE, "savefig.facecolor": SURFACE,
    "axes.edgecolor": INK3, "axes.labelcolor": INK, "text.color": INK,
    "xtick.color": INK2, "ytick.color": INK2, "axes.linewidth": 0.8,
    "grid.color": "#e6e5e1", "grid.linewidth": 0.7, "font.size": 9,
    "axes.titlesize": 10, "legend.frameon": False, "figure.dpi": 200,
})

# display name -> how a run is recognised. Order is the order they appear in the paper.
def arm_of(c):
    if c["supply"] == "autoreg":
        if c["autoreg_gain"] != 0.003:
            return None                                   # undamped, reported separately
        return "autoreg + stall gate" if c.get("stall_gate", 0) > 0 else "autoreg"
    if c["supply"] == "poiseuille":
        return f"poiseuille $n{{=}}{c['flow_exponent']:g}$"
    if c["supply"] in ("threshold", "gap", "otsu", "watershed"):
        if c["demand"] != "outnorm_ema":
            return None
        return {"threshold": "fixed threshold"}.get(c["supply"], c["supply"])
    return None


def load():
    d = collections.defaultdict(list)
    for p in glob.glob(os.path.join(ROOT, "results", "*st4000*.pkl")):
        with open(p, "rb") as f:
            r = pickle.load(f)
        c = r["cfg"]
        if (c["task"] != "multi_relation" or c["pool_beta"] or c["leak"] or c["delay"]
                or c.get("target_frac", 0.02) != 0.02):
            continue
        a = arm_of(c)
        if a is None:
            continue
        led = r["hist"]["ledger"]
        hold = int((c["budget_hold_frac"] + c["budget_anneal_frac"]) * len(led))
        B = np.median((led[hold:] > 1e-9).sum(axis=1))
        d[(a, c["n_rel"])].append((B, r["final_loss"], r["recovery"]["role_coverage"]))
    return d


def stats(d):
    out = {}
    for arm in {k[0] for k in d}:
        Rs = sorted(R for (a, R) in d if a == arm)
        B = [float(np.mean([x[0] for x in d[(arm, R)]])) for R in Rs]
        cov = [float(np.mean([x[2] for x in d[(arm, R)]])) for R in Rs]
        loss = [float(np.mean([x[1] for x in d[(arm, R)]])) for R in Rs]
        n = min(len(d[(arm, R)]) for R in Rs)
        slope = float(np.polyfit(Rs, B, 1)[0]) if len(Rs) >= 3 else float("nan")
        mae = float(np.mean([abs(b - R) for R, b in zip(Rs, B)]))
        out[arm] = dict(Rs=Rs, B=B, slope=slope, mae=mae, cov=float(np.nanmean(cov)),
                        loss=float(np.mean(loss)), n=n)
    return out


def write_table(st, path):
    order = sorted(st, key=lambda a: (abs(st[a]["slope"] - 1.0)
                                      if st[a]["slope"] == st[a]["slope"] else 9))
    lines = [r"% GENERATED by experiments/paper_assets.py. Do not edit.",
             r"\begin{tabular}{lrrrrr}", r"\toprule",
             r"supply rule & $\mathrm{d}B/\mathrm{d}k^\star$ & MAE (heads) & "
             r"role cov. & val MSE & seeds \\", r"\midrule"]
    for a in order:
        s = st[a]
        sl = "--" if s["slope"] != s["slope"] else f"{s['slope']:.2f}"
        name = r"\textbf{" + a + "}" if a.startswith("autoreg + stall") else a
        eol = r" \\"
        lines.append(f"{name} & {sl} & " + f"{s['mae']:.2f} & {s['cov']:.2f} & "
                     + f"{s['loss']:.4f} & {s['n']}" + eol)
    lines += [r"\midrule",
              r"ideal & 1.00 & 0.00 & 1.00 & --- & --- \\",
              r"\bottomrule", r"\end{tabular}"]
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    return order


def fig_arms(st, order, path):
    fig, axes = plt.subplots(1, 2, figsize=(9.6, 3.6))
    ax = axes[0]
    allR = sorted({R for a in st for R in st[a]["Rs"]})
    lim = [min(allR) - 0.5, max(allR) + 0.5]
    ax.plot(lim, lim, color=INK3, lw=1.4, ls=":", label=r"$B=k^\star$")
    for i, a in enumerate(order[:6]):
        s = st[a]
        auto = a.startswith("autoreg")
        # the two closed-loop arms coincide exactly, so the second is dashed and nudged
        # rather than drawn invisibly underneath the first
        dy = 0.10 if a.startswith("autoreg + ") else 0.0
        ax.plot(s["Rs"], [b + dy for b in s["B"]], color=CAT[i % len(CAT)],
                lw=2.6 if auto else 1.6, ls="--" if dy else "-",
                marker="o", ms=5.5 if auto else 4.5, label=a,
                zorder=6 if auto else 2)
    ax.set_xticks(allR); ax.set_xlim(*lim)
    ax.set_xlabel(r"true circuit size $k^\star$")
    ax.set_ylabel(r"perfused heads $B$")
    ax.set_title("a   Does the perfused count follow the task?", loc="left",
                 fontweight="bold")
    ax.grid(axis="y", alpha=0.9); ax.set_axisbelow(True)
    for sp in ("top", "right"):
        ax.spines[sp].set_visible(False)
    ax.legend(loc="upper left", fontsize=7.2)

    ax = axes[1]
    ok = [a for a in order if st[a]["slope"] == st[a]["slope"]]
    y = np.arange(len(ok))
    sl = [st[a]["slope"] for a in ok]
    ax.barh(y, sl, height=0.62, color=[CAT[0] if v >= 0 else CAT[7] for v in sl],
            edgecolor=SURFACE, linewidth=1.6)
    ax.axvline(1.0, color=GOOD, lw=1.6, ls="--")
    ax.text(1.0, -0.72, "ideal", color=GOOD, fontsize=8, va="center", ha="center")
    ax.axvline(0, color=INK3, lw=1)
    for i, v in enumerate(sl):
        inside = v < -0.15                  # negative labels sit inside the bar, so they
        ax.annotate(f"{v:+.2f}", (v, i),    # cannot collide with the row names
                    textcoords="offset points",
                    xytext=(6 if (v >= 0 or not inside) else 6, 0),
                    va="center", ha="left",
                    fontsize=7.5, color="white" if inside else INK2,
                    fontweight="bold" if inside else "normal")
    ax.set_yticks(y); ax.set_yticklabels(ok, fontsize=8)
    ax.set_xlim(min(-1.05, min(sl) - 0.1), 1.25)
    ax.invert_yaxis()
    ax.set_xlabel(r"fitted $\mathrm{d}B/\mathrm{d}k^\star$")
    ax.set_title("b   Only the closed loop tracks circuit size", loc="left",
                 fontweight="bold")
    ax.grid(axis="x", alpha=0.9); ax.set_axisbelow(True)
    for sp in ("top", "right", "left"):
        ax.spines[sp].set_visible(False)
    fig.tight_layout()
    fig.savefig(path, bbox_inches="tight")
    plt.close(fig)


def main():
    d = load()
    if not d:
        print("no runs"); return
    st = stats(d)
    os.makedirs(os.path.join(ROOT, "paper"), exist_ok=True)
    order = write_table(st, os.path.join(ROOT, "paper", "results_table.tex"))
    fig_arms(st, order, os.path.join(ROOT, "figures", "fig_arms.png"))
    for a in order:
        s = st[a]
        print(f"{a:<26} slope {s['slope']:>6.2f}  MAE {s['mae']:>5.2f}  "
              f"cov {s['cov']:.2f}  loss {s['loss']:.4f}  n={s['n']}  "
              f"B={[round(b,1) for b in s['B']]} at k*={s['Rs']}")
    print("\nwrote paper/results_table.tex and figures/fig_arms.png")


if __name__ == "__main__":
    main()

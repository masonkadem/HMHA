"""Generates the paper's results table and its comparison figure from results/*.pkl.

Writes paper/results_table.tex, which paper/main.tex \\input{}s, so no number in the
paper is transcribed by hand. Also writes figures/fig_arms.png.

  python experiments/paper_assets.py
"""
import glob, os, pickle, sys, collections
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "src"))

SURFACE = "#fcfcfb"
CAT = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300", "#4a3aa7",
       "#e34948"]
INK, INK2, INK3 = "#0b0b0b", "#52514e", "#8a8880"
GOOD, CRIT = "#0ca30c", "#d03b3b"
plt.rcParams.update({
    "figure.facecolor": SURFACE, "axes.facecolor": SURFACE, "savefig.facecolor": SURFACE,
    "axes.edgecolor": INK3, "axes.labelcolor": INK, "text.color": INK,
    "xtick.color": INK2, "ytick.color": INK2, "axes.linewidth": 0.8,
    "grid.color": "#e6e5e1", "grid.linewidth": 0.7, "font.size": 9,
    "axes.titlesize": 10, "legend.frameon": False, "figure.dpi": 200,
})

# display name -> how a run is recognised. Order is the order they appear in the paper.
def arm_of(c):
    if c["supply"] == "autoreg":
        if c["autoreg_gain"] != 0.003:
            return None                                   # undamped, reported separately
        return "autoreg + stall gate" if c.get("stall_gate", 0) > 0 else "autoreg"
    if c["supply"] == "poiseuille":
        return f"poiseuille $n{{=}}{c['flow_exponent']:g}$"
    if c["supply"] in ("threshold", "gap", "otsu", "watershed"):
        if c["demand"] != "outnorm_ema":
            return None
        return {"threshold": "fixed threshold"}.get(c["supply"], c["supply"])
    return None


def load():
    d = collections.defaultdict(list)
    for p in glob.glob(os.path.join(ROOT, "results", "*st4000*.pkl")):
        with open(p, "rb") as f:
            r = pickle.load(f)
        c = r["cfg"]
        if (c["task"] != "multi_relation" or c["pool_beta"] or c["leak"] or c["delay"]
                or c.get("target_frac", 0.02) != 0.02):
            continue
        a = arm_of(c)
        if a is None:
            continue
        led = r["hist"]["ledger"]
        hold = int((c["budget_hold_frac"] + c["budget_anneal_frac"]) * len(led))
        B = np.median((led[hold:] > 1e-9).sum(axis=1))
        d[(a, c["n_rel"])].append((B, r["final_loss"], r["recovery"]["role_coverage"]))
    return d


def stats(d):
    out = {}
    for arm in {k[0] for k in d}:
        Rs = sorted(R for (a, R) in d if a == arm)
        B = [float(np.mean([x[0] for x in d[(arm, R)]])) for R in Rs]
        cov = [float(np.mean([x[2] for x in d[(arm, R)]])) for R in Rs]
        loss = [float(np.mean([x[1] for x in d[(arm, R)]])) for R in Rs]
        n = min(len(d[(arm, R)]) for R in Rs)
        slope = float(np.polyfit(Rs, B, 1)[0]) if len(Rs) >= 3 else float("nan")
        mae = float(np.mean([abs(b - R) for R, b in zip(Rs, B)]))
        out[arm] = dict(Rs=Rs, B=B, slope=slope, mae=mae, cov=float(np.nanmean(cov)),
                        loss=float(np.mean(loss)), n=n)
    return out


CLOSED = ("autoreg", "autoreg + stall gate")


def write_table(st, path):
    """Grouped by what the paper argues: closed loop against open loop. All arms are
    itemised here even though the figure collapses the failures, because the open-loop
    rules that are NOT fixed-quantile (gap, otsu) are evidence the failure is broader
    than Theorem 1 proves."""
    def block(names):
        out = []
        for a in sorted(names, key=lambda a: -(st[a]["slope"] if st[a]["slope"] == st[a]["slope"] else -9)):
            v = st[a]
            sl = "---" if v["slope"] != v["slope"] else f"{v['slope']:+.2f}"
            nm = r"\textbf{" + a + "}" if a == "autoreg + stall gate" else a
            out.append(f"{nm} & {sl} & " + f"{v['mae']:.2f} & {v['cov']:.2f} & "
                       + f"{v['loss']:.4f} & {v['n']}" + r" \\")
        return out

    closed = [a for a in st if a in CLOSED]
    openl = [a for a in st if a not in CLOSED]
    L = [r"% GENERATED by experiments/paper_assets.py. Do not edit.",
         r"\begin{tabular}{@{}lccccc@{}}", r"\toprule",
         r"& $\mathrm{d}B/\mathrm{d}k^\star$ & MAE & role & val & \\\\",
         r"supply rule & (ideal $1.00$) & (heads) & cov. & MSE & $n$ \\",
         r"\midrule",
         r"\multicolumn{6}{@{}l}{\emph{closed loop: supply answers to a metabolic deficit}} \\"]
    L += block(closed)
    L += [r"\addlinespace[2pt]", r"\midrule",
          r"\multicolumn{6}{@{}l}{\emph{open loop: supply answers to the demand distribution}} \\"]
    L += block(openl)
    L += [r"\bottomrule", r"\end{tabular}"]
    with open(path, "w") as f:
        f.write("\n".join(L) + "\n")
    return sorted(st, key=lambda a: -(st[a]["slope"] if st[a]["slope"] == st[a]["slope"] else -9))


def fig_arms(st, order, path):
    """Three things are shown and nothing else: the closed loop, the rule Theorem 1 is
    about, and the envelope of everything else. Eight labelled series is a table."""
    MUTE, BAND = "#9c9a93", "#e9e7e1"
    fig, axes = plt.subplots(1, 2, figsize=(10.6, 3.8),
                             gridspec_kw=dict(width_ratios=[1.0, 1.0], wspace=0.34))

    # ---------------- a: tracking ----------------
    ax = axes[0]
    allR = sorted({R for a in st for R in st[a]["Rs"]})
    others = [a for a in st if a not in CLOSED and a != "fixed threshold"
              and len(st[a]["Rs"]) >= 3]
    grid = [R for R in allR if all(R in st[a]["Rs"] for a in others)] or allR
    lo = [min(np.interp(R, st[a]["Rs"], st[a]["B"]) for a in others) for R in grid]
    hi = [max(np.interp(R, st[a]["Rs"], st[a]["B"]) for a in others) for R in grid]
    ax.fill_between(grid, lo, hi, color=BAND, zorder=0, lw=0)
    ax.plot(grid, hi, color=MUTE, lw=0.9, zorder=1)
    ax.plot(grid, lo, color=MUTE, lw=0.9, zorder=1)
    ytop = max(allR) + 5.5
    xi = int(np.argmax(hi))
    ax.annotate("other open-loop rules\n(range, $n{=}%d$)" % len(others),
                (grid[min(xi + 1, len(grid) - 1)], min(ytop * 0.90, max(hi))),
                textcoords="offset points", xytext=(4, -4), fontsize=7.8,
                color=INK2, va="top", ha="left")

    ax.plot(allR, allR, color=INK3, lw=1.0, ls=(0, (1, 2.4)), zorder=2)
    ax.annotate(r"$B=k^\star$", (allR[0], allR[0]), textcoords="offset points",
                xytext=(-2, 11), fontsize=8, color=INK3, style="italic",
                va="bottom", ha="left")

    ft = st.get("fixed threshold")
    if ft:
        ax.plot(ft["Rs"], ft["B"], color=CAT[1], lw=2.0, marker="o", ms=5.4,
                mfc=SURFACE, mew=1.7, mec=CAT[1], zorder=5, solid_capstyle="round")
        ax.annotate("fixed threshold", (ft["Rs"][-1], ft["B"][-1]),
                    textcoords="offset points", xytext=(8, -9), fontsize=8.4,
                    color=CAT[1], va="center")
    # the two closed-loop arms give identical B, so one line carries both; the stall
    # gate's contribution is role recovery, which panel b and the table report
    cl = max((a for a in CLOSED if a in st), key=lambda a: len(st[a]["Rs"]), default=None)
    if cl:
        v = st[cl]
        ax.plot(v["Rs"], v["B"], color=CAT[0], lw=2.9, marker="o", ms=6.0,
                mfc=SURFACE, mew=2.0, mec=CAT[0], zorder=6, solid_capstyle="round")
        ax.annotate("autoregulated\nsupply", (v["Rs"][-1], v["B"][-1]),
                    textcoords="offset points", xytext=(9, 3), fontsize=8.6,
                    color=CAT[0], va="center", fontweight="bold")
        ax.annotate("both closed-\nloop arms", (v["Rs"][-1], v["B"][-1]),
                    textcoords="offset points", xytext=(9, -20), fontsize=7.4,
                    color=CAT[0], va="center")
    ax.set_xticks(allR)
    ax.set_xlim(allR[0] - 0.5, allR[-1] + 3.4)
    ax.set_ylim(0, ytop)
    ax.set_xlabel(r"true circuit size $k^\star$", fontsize=9.5)
    ax.set_ylabel(r"perfused heads $B$", fontsize=9.5)
    ax.set_title("a   The perfused count against the task", loc="left", color=INK,
                 fontsize=10.5, fontweight="bold", pad=9)
    ax.grid(axis="y", alpha=0.7, lw=0.7); ax.set_axisbelow(True)
    for sp in ("top", "right"):
        ax.spines[sp].set_visible(False)

    # ---------------- b: slope, as a lollipop with a value column ----------------
    ax = axes[1]
    ok = [a for a in order if st[a]["slope"] == st[a]["slope"]]
    y = np.arange(len(ok))
    sl = [st[a]["slope"] for a in ok]
    cols = [CAT[0] if a in CLOSED else (CAT[1] if a == "fixed threshold" else MUTE)
            for a in ok]
    XCOL = 1.62                                        # fixed column for the numbers
    ax.axvline(1.0, color=GOOD, lw=1.3, ls=(0, (4, 3)), zorder=1)
    ax.axvline(0, color=INK3, lw=0.9, zorder=2)
    ax.hlines(y, 0, sl, color=cols, lw=2.6, zorder=3)
    ax.scatter(sl, y, s=66, c=cols, zorder=4, edgecolor=SURFACE, linewidth=1.5)
    for i_, (a, v) in enumerate(zip(ok, sl)):
        ax.annotate(f"{v:+.2f}", (XCOL, i_), fontsize=8.4, va="center", ha="right",
                    color=INK if a in CLOSED else INK2,
                    fontweight="bold" if a in CLOSED else "normal")
    ax.set_yticks(y)
    ax.set_yticklabels(ok, fontsize=8.3)
    for t, a in zip(ax.get_yticklabels(), ok):
        t.set_color(INK if a in CLOSED else INK2)
        if a in CLOSED:
            t.set_fontweight("bold")
    ax.tick_params(axis="y", length=0)
    ax.set_xlim(min(-1.12, min(sl) - 0.12), XCOL + 0.04)
    ax.set_ylim(len(ok) - 0.4, -1.15)
    ax.set_xticks([-1, -0.5, 0, 0.5, 1])
    ax.annotate("ideal", (1.0, -0.85), fontsize=8, color=GOOD, ha="center")
    ax.annotate(r"$\mathrm{d}B/\mathrm{d}k^\star$", (XCOL, -0.85), fontsize=8,
                color=INK2, ha="right")
    ax.set_xlabel(r"fitted slope", fontsize=9.5)
    ax.set_title("b   Only the closed loop tracks it", loc="left", color=INK,
                 fontsize=10.5, fontweight="bold", pad=9)
    ax.grid(axis="x", alpha=0.55, lw=0.7); ax.set_axisbelow(True)
    for sp in ("top", "right", "left", "bottom"):
        ax.spines[sp].set_visible(False)
    fig.savefig(path, bbox_inches="tight", pad_inches=0.07)
    plt.close(fig)


def main():
    d = load()
    if not d:
        print("no runs"); return
    st = stats(d)
    os.makedirs(os.path.join(ROOT, "paper"), exist_ok=True)
    order = write_table(st, os.path.join(ROOT, "paper", "results_table.tex"))
    fig_arms(st, order, os.path.join(ROOT, "figures", "fig_arms.png"))
    for a in order:
        s = st[a]
        print(f"{a:<26} slope {s['slope']:>6.2f}  MAE {s['mae']:>5.2f}  "
              f"cov {s['cov']:.2f}  loss {s['loss']:.4f}  n={s['n']}  "
              f"B={[round(b,1) for b in s['B']]} at k*={s['Rs']}")
    print("\nwrote paper/results_table.tex and figures/fig_arms.png")


if __name__ == "__main__":
    main()
